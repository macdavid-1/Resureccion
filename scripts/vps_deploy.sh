#!/bin/sh
# One-command deploy for Resurrección on a fresh VPS.
#
#   git clone <repo> ~/resurreccion && cd ~/resurreccion
#   sudo sh scripts/vps_deploy.sh
#
# That is the whole thing. It provisions the host, scaffolds a .env with
# generated secrets, creates the durable data directory the SQLite database
# lives in, installs the PDF sidecar's Node deps, and starts the app under
# pm2 — then waits until /api/health answers and prints the URL.
#
# Idempotent and safe to re-run: it is also the update path. Re-running it
# pulls the latest code state you already have, re-provisions whatever is
# missing, and restarts the app. Your .env is never overwritten.
#
# Flags are forwarded to scripts/vps_provision.sh:
#   --no-swap    keep the host's existing swap
#   --with-ufw   also enable the firewall (SSH + app port only)
set -eu

cd "$(dirname "$0")/.."
PROJECT_DIR=$(pwd)

APP_PORT=7860
PM2_APP=resurreccion

say() { printf '\n==> %s\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# Owner account
# ---------------------------------------------------------------------------
# pm2 must run as a normal user, not root: the browser profile and the SQLite
# database live under that user's DATA_DIR, and root-owned files would make
# the next non-root boot fail. When invoked through sudo we adopt SUDO_USER.
OWNER_USER="${SUDO_USER:-$(id -un)}"
OWNER_HOME=$(getent passwd "$OWNER_USER" 2>/dev/null | cut -d: -f6)
[ -n "$OWNER_HOME" ] || OWNER_HOME="$HOME"

run_as_owner() {
  if [ "$(id -u)" -eq 0 ] && [ "$OWNER_USER" != "root" ]; then
    sudo -u "$OWNER_USER" -H env HOME="$OWNER_HOME" PATH="$PATH" "$@"
  else
    "$@"
  fi
}

# dash has no `read -s`, so drop echo by hand. Never prints the value.
secret_prompt() {
  printf '%s' "$1" >&2
  if [ -t 0 ]; then stty -echo; fi
  _v=""
  IFS= read -r _v || _v=""
  if [ -t 0 ]; then stty echo; printf '\n' >&2; fi
  printf '%s' "$_v"
}

# ---------------------------------------------------------------------------
# 0. Preflight
# ---------------------------------------------------------------------------
if [ "$(id -u)" -ne 0 ]; then
  die "needs root for packages and swap — re-run with sudo"
fi
for req in curl git; do
  command -v "$req" >/dev/null 2>&1 || die "$req is required"
done

# ---------------------------------------------------------------------------
# 1. Provision the host (packages, swap, venv, pm2, browser binary)
# ---------------------------------------------------------------------------
say "Provisioning the host"
sh scripts/vps_provision.sh "$@"

# The venv now exists — resolve the interpreter the app will actually use.
if [ -x "$PROJECT_DIR/.venv/bin/python" ]; then
  PY="$PROJECT_DIR/.venv/bin/python"
else
  PY="python3"
fi

# ---------------------------------------------------------------------------
# 2. Secrets: scaffold .env once, never overwrite it
# ---------------------------------------------------------------------------
if [ -f .env ]; then
  say ".env already present — leaving it untouched"
else
  say "Creating .env"

  OWNER_USERNAME="owner"
  AUTH_SECRET=$("$PY" -c 'import secrets; print(secrets.token_urlsafe(48))')

  # Password: asked for on a terminal, generated when not (headless/CI). A
  # generated password is written into .env and printed once, because the
  # owner cannot sign in without it and there is no reset flow — it is
  # single-user, single-device, and meant to be changed immediately.
  GENERATED_PW=""
  if [ -t 0 ]; then
    PW=$(secret_prompt "Choose a password for the app login: ")
    [ -n "$PW" ] || die "password must not be empty"
    PW2=$(secret_prompt "Confirm password: ")
    [ "$PW" = "$PW2" ] || die "passwords did not match"
  else
    PW=$("$PY" -c 'import secrets; print(secrets.token_urlsafe(18))')
    GENERATED_PW="$PW"
  fi
  PW_HASH=$(PYTHONPATH="$PROJECT_DIR" "$PY" - "$PW" <<'PYEOF'
import sys
from app.security import hash_password
print(hash_password(sys.argv[1]))
PYEOF
)

  MODEL_API_KEY=""
  if [ -t 0 ]; then
    printf 'DeepInfra API key (leave blank to add it later): ' >&2
    IFS= read -r MODEL_API_KEY || MODEL_API_KEY=""
  fi

  # umask first: this file holds the owner password hash and the API key.
  ( umask 077 && cat > .env <<ENVEOF
# Resurrección — generated by scripts/vps_deploy.sh. Secrets only; safe to
# edit, never committed. Every value here overrides the built-in defaults.

OWNER_USERNAME=$OWNER_USERNAME
OWNER_PASSWORD_HASH=$PW_HASH
AUTH_SECRET=$AUTH_SECRET

# Research model (required before a research run will start).
MODEL_API_KEY=$MODEL_API_KEY
MODEL_BASE_URL=https://api.deepinfra.com/v1/openai
MODEL_NAME=XiaomiMiMo/MiMo-V2.6-Flash

# Durable storage: the SQLite database and every artifact live here.
DATA_DIR=$OWNER_HOME/resurreccion-data
PORT=$APP_PORT

# Sized for a 4 vCPU / 8 GB box by scripts/vps_provision.sh.
BROWSER_CONTENT_PROCESSORS=3
ENVEOF
  )

  if [ -n "$GENERATED_PW" ]; then
    say "Generated login password (change it in the app, then edit .env):"
    printf '    %s\n' "$GENERATED_PW"
  fi
  [ -n "$MODEL_API_KEY" ] || say "MODEL_API_KEY is empty — add it to .env before running research"
fi

# shellcheck disable=SC1091
set -a; . ./.env; set +a
APP_PORT="${PORT:-7860}"

# ---------------------------------------------------------------------------
# 3. Durable storage — where the SQLite database lives
# ---------------------------------------------------------------------------
say "Ensuring the data directory"
DATA_DIR="${DATA_DIR:-$OWNER_HOME/resurreccion-data}"
run_as_owner mkdir -p "$DATA_DIR"
# The database is created on first boot; make sure the owner can write it.
run_as_owner touch "$DATA_DIR/.writable" && rm -f "$DATA_DIR/.writable"

# ---------------------------------------------------------------------------
# 4. Node sidecar (PDF export)
# ---------------------------------------------------------------------------
if [ -f package.json ] && [ ! -d node_modules/pdfkit ]; then
  say "Installing the PDF sidecar's Node dependencies"
  run_as_owner npm install --no-audit --no-fund || \
    echo "NOTE: npm install failed; PDF export will be disabled" >&2
fi

# ---------------------------------------------------------------------------
# 5. Start under pm2
# ---------------------------------------------------------------------------
say "Starting $PM2_APP under pm2"
run_as_owner npm install -g pm2 --no-audit --no-fund >/dev/null 2>&1 || true

# `pm2 start` on an already-registered app would spawn a second entry; delete
# the old one first so re-runs restart rather than duplicate.
if run_as_owner pm2 describe "$PM2_APP" >/dev/null 2>&1; then
  run_as_owner pm2 delete "$PM2_APP" >/dev/null
fi
run_as_owner pm2 start ecosystem.config.cjs >/dev/null
run_as_owner pm2 save >/dev/null

# Register pm2 to come back after a reboot. Best effort: it needs systemd and
# a writable /etc/systemd, and a failure here must not fail the deploy.
run_as_owner pm2 startup systemd >/dev/null 2>&1 || \
  echo "NOTE: pm2 could not register a boot hook; run 'pm2 startup' yourself" >&2

# ---------------------------------------------------------------------------
# 6. Verify
# ---------------------------------------------------------------------------
say "Waiting for the app to answer on :$APP_PORT"
READY=0
i=0
while [ "$i" -lt 60 ]; do
  if curl -fsS --max-time 3 "http://127.0.0.1:$APP_PORT/api/health" >/dev/null 2>&1; then
    READY=1
    break
  fi
  i=$((i + 1))
  sleep 2
done

if [ "$READY" -ne 1 ]; then
  printf '\nDeploy finished but the app did not answer in time.\n' >&2
  printf '  logs:  pm2 logs %s\n' "$PM2_APP" >&2
  printf '  health: curl -fsS http://127.0.0.1:%s/api/health\n' "$APP_PORT" >&2
  exit 1
fi

say "Deployed and healthy"
printf '  URL:      http://<your-server-ip>:%s\n' "$APP_PORT"
printf '  Login:    the password you chose (or the one printed above)\n'
printf '  Database: %s\n' "$DATA_DIR"
printf '  Logs:     pm2 logs %s\n' "$PM2_APP"
printf '  Restart:  pm2 restart %s\n' "$PM2_APP"
printf '\nNext: open the app, sign in, then Settings → Amazon sign-in and KDSpy.\n'
